CREATE OR REPLACE FUNCTION get_customer_revenue(p_customer_id INT)
RETURNS NUMERIC
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_revenue NUMERIC;
BEGIN
    SELECT COALESCE(SUM(total_amount), 0)
    INTO v_revenue
    FROM orders
    WHERE customer_id = p_customer_id
      AND status = 'Completed';

    RETURN v_revenue;
END;
$$;

--45.Segment customers into High, Medium and Low Value, and explain why you chose your thresholds.
WITH customer_revenue AS (
    SELECT
        c.customer_id,
        c.customer_name,
        COALESCE(SUM(o.quantity*unit_price), 0) AS revenue
    FROM customers c
    LEFT JOIN orders o
           ON o.customer_id = c.customer_id
          AND o.order_status = 'Completed'
    GROUP BY c.customer_id, c.customer_name
),
thresholds AS (
    SELECT
        PERCENTILE_CONT(0.8) WITHIN GROUP (ORDER BY revenue) AS p80,
        PERCENTILE_CONT(0.4) WITHIN GROUP (ORDER BY revenue) AS p40
    FROM customer_revenue
)
SELECT
    cr.customer_id,
    cr.customer_name,
    cr.revenue,
    CASE
        WHEN cr.revenue > 0 AND cr.revenue >= t.p80 THEN 'High'
        WHEN cr.revenue > 0 AND cr.revenue >= t.p40 THEN 'Medium'
        ELSE 'Low'
    END AS segment
FROM customer_revenue cr
CROSS JOIN thresholds t
ORDER BY cr.revenue DESC;


